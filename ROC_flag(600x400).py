import turtle

t = turtle.Turtle()
t.speed(10)

# red rectangle (600x400)
t.penup()
t.goto(-300, -200)
t.color("red")
t.pendown()
t.begin_fill()
for i in range(2):
    t.forward(600)
    t.left(90)
    t.forward(400)
    t.left(90)
t.end_fill()
t.penup()

# blue rectangle (300x200)
t.goto(-300, 0)
t.color("blue")
t.pendown()
t.begin_fill()
for i in range(2):
    t.forward(300)
    t.left(90)
    t.forward(200)
    t.left(90)
t.end_fill()
t.penup()

# white triangle * 12
t.color("white")
t.goto(-150, 175)
t.right(105)
for i in range(12):
    t.pendown()
    t.begin_fill()
    t.forward(int(75 * ((6**0.5) - (2**0.5))))  # 75(√6-√2)
    t.left(105)
    t.forward(int(2 * (150 - 75 * (3**0.5))))  # 2(150-75√3)
    t.left(105)
    t.forward(int(75 * ((6**0.5) - (2**0.5))))  # 75(√6-√2)
    t.end_fill()
    t.penup()
    t.right(120)
    t.forward(int(37.5 * ((6**0.5) - (2**0.5))))  # 37.5(√6-√2)
    t.right(120)

# blue circle (r=42.5)
t.color("blue")
t.left(105)
t.goto(-150, 57.5)
t.pendown()
t.begin_fill()
t.circle(42.5)
t.end_fill()
t.penup()

# white circle (r=37.5)
t.color("white")
t.goto(-150, 62.5)
t.pendown()
t.begin_fill()
t.circle(37.5)
t.end_fill()
t.penup()

t.hideturtle()
turtle.done()
